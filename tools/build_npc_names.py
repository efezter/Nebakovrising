"""Stable generated names for the mod's own Skald/soul identities and UI labels."""
from pathlib import Path
import random
import re
import xml.etree.ElementTree as ET
import zipfile

ROOT=Path(__file__).resolve().parents[1]
MALE='Marek Hertl Jan Petr Tomas Martin Pavel Ondrej Lukas Karel Vaclav Jiri Jakub Matej Vitek Radek Bohdan Oldrich Zdenek Jaroslav Miroslav Stanislav Ladislav Viktor Roman Simon Adam Daniel Filip Mikulas Prokop Vojtech Bohuslav Hynek Ctibor Dalibor Bedrich Borivoj Zbynek Frantisek'.split()
FEMALE='Alena Anna Barbora Dorota Eliska Hana Katerina Ludmila Magdalena Zuzana'.split()

def build():
    rng=random.Random(20261026)
    pools={0:MALE[:],1:FEMALE[:]}
    for names in pools.values():rng.shuffle(names)
    path=ROOT/'src/libs/tables/skald/skald_character__nebakovrising.xml'
    text=path.read_text(encoding='utf-8')
    names={};rows=[]
    def replace(match):
        row=ET.fromstring(match.group())
        identity=row.get('skald_character_name')
        if not identity.startswith('char_nebakov_'):return match.group()
        name=pools[int(row.get('gender'))].pop()
        key=identity+'_uiName';names[identity]=(name,key)
        s=match.group()
        for field in ('description_string_name','skald_character_full_name_string_name','ui_name_string_name'):
            s=re.sub(field+r'="[^"]*"',field+'="'+key+'"',s)
        rows.append((key,name))
        return s
    text=re.sub(r'<skald_character\s[^>]+/>',replace,text)
    path.write_text(text,encoding='utf-8')
    souls=ET.parse(ROOT/'src/libs/tables/rpg/soul__nebakovrising.xml').getroot()
    lines=['-- Generated by tools/build_npc_names.py; UI and prompt identities agree.',
           'nebakovrising.NpcNamesData={souls={},keys={}}','local D=nebakovrising.NpcNamesData']
    for row in souls.iter('soul'):
        name,key=names[row.get('skald_character_name')]
        lines.append('D.souls["%s"]={name="%s",key="%s"}'%(row.get('soul_id').lower(),name,key))
        lines.append('D.keys["%s"]="%s"'%(key,name))
    (ROOT/'src/Scripts/mods/NpcNamesData.lua').write_text('\n'.join(lines)+'\n',encoding='ascii')
    table=ET.Element('Table')
    for key,name in rows:
        row=ET.SubElement(table,'Row')
        for value in (key,name,name):ET.SubElement(row,'Cell').text=value
    folder=ROOT/'localization_src';folder.mkdir(exist_ok=True)
    ET.indent(table)
    ET.ElementTree(table).write(folder/'text__nebakovrising.xml',encoding='utf-8',xml_declaration=True)
    print('Generated stable UI/prompt names for',len(rows),'mod character identities.')

def build_localization():
    source=ROOT/'localization_src/text__nebakovrising.xml'
    folder=ROOT/'Localization';folder.mkdir(exist_ok=True)
    destination=folder/'english_xml.pak'
    temporary=folder/'english_xml.pak.tmp'
    with zipfile.ZipFile(temporary,'w',zipfile.ZIP_DEFLATED) as pak:pak.write(source,source.name)
    with zipfile.ZipFile(temporary) as pak:
        assert pak.testzip() is None and pak.read(source.name)==source.read_bytes()
    temporary.replace(destination)
    print('Built and verified:',destination)

if __name__=='__main__':build();build_localization()
